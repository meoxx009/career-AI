-- Public seed/read-only data. Grant only the operations the UI needs.
create policy "authenticated users read active skills" on public.skills for select to authenticated using (active = true);
create policy "authenticated users read active roles" on public.career_roles for select to authenticated using (active = true);
create policy "authenticated users read role skills" on public.role_skills for select to authenticated using (true);
create policy "authenticated users read active questions" on public.assessment_questions for select to authenticated using (active = true);

create policy "users read own profile" on public.profiles for select to authenticated using (auth.uid() = id);
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "users delete own profile" on public.profiles for delete to authenticated using (auth.uid() = id);

create policy "users own assessment attempts" on public.assessment_attempts for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own assessment answers" on public.assessment_answers for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own observations" on public.skill_observations for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own roadmaps" on public.roadmaps for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own roadmap tasks" on public.roadmap_tasks for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own resumes" on public.resume_documents for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own resume analyses" on public.resume_analyses for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own interview sessions" on public.interview_sessions for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users own events" on public.events for insert to authenticated with check (auth.uid() = user_id);
create policy "users read own events" on public.events for select to authenticated using (auth.uid() = user_id);
